#!/usr/bin/env node
"use strict";
// ============================================================
// generate_game_balance.js — job: regenerate dev/docs/game_balance.md from
// the frozen data tables (rules_DATA.js, campaign_DATA.js), so the balance
// document can never drift from the data silently. Tooling only (dev/scripts,
// §5) — no game code depends on it.
//
//   node dev/scripts/generate_game_balance.js vNN    regenerate + write the doc
//   node dev/scripts/generate_game_balance.js --check  exit 0 iff the checked-in
//                                                      doc matches a fresh
//                                                      regeneration byte-for-byte
//                                                    (version taken from the
//                                                    doc's own title line)
// ============================================================

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "..", "..");
const RULES_REL = "main.js children/game.js children/rules_DATA.js";
const CAMPAIGN_REL = "main.js children/game.js children/campaign_DATA.js";
const OUT_REL = "dev/docs/game_balance.md";

function loadPayload(rel, constName) {
  const src = fs.readFileSync(path.join(REPO_ROOT, rel), "utf8");
  return new Function(src + "\nreturn " + constName + ";")();
}

function fmt(n) {
  const s = String(Math.round(n));
  let out = "";
  for (let i = 0; i < s.length; i++) {
    if (i > 0 && (s.length - i) % 3 === 0) out += ",";
    out += s[i];
  }
  return out;
}

function pct(x) {
  return String(Math.round(x * 100)) + "%";
}

function generateGameBalance(version) {
  const R = loadPayload(RULES_REL, "rulesDataPayload");
  const C = loadPayload(CAMPAIGN_REL, "campaignDataPayload");
  const L = [];

  L.push("# Game Balance — Seek & Destroy (" + version + ")");
  L.push("");
  L.push("*Generated by `dev/scripts/generate_game_balance.js` from");
  L.push("`" + RULES_REL + "` and `" + CAMPAIGN_REL + "`. Do not edit by hand —");
  L.push("regenerate. All money values are on the ×100 economy scale (DESIGN §4.5).*");
  L.push("");

  // Core constants
  const z = R.zoomLadder, cr = R.combatRules;
  L.push("## Core constants");
  L.push("");
  L.push(fmt(R.gridSize) + "×" + fmt(R.gridSize) + " grid; **" + R.maxAp + " AP per turn** (`maxAp`); warp-in / spawn radius **R:" + R.spawnRadius + "**; zoom ladder " + z[0] + "→" + z[z.length - 1] + " (" + z.length + " steps, wheel notch " + R.wheelNotchPx + " px, ≤" + R.maxZoomStepsPerEvent + " steps per event). Nebulae: effective scan " + cr.nebulaEffectiveScan + ", cloak at d ≤ " + cr.nebulaCloakDist + ". Shields: non-railgun hit on a raised bubble deals " + cr.shieldNonRailgunDamage + " damage + strip; a raised bubble adds +" + cr.shieldCollisionBonus + " effective HP in a ram. Default difficulty " + R.defaultDifficulty + ".");
  L.push("");

  // Difficulty profiles
  const dp = R.difficultyProfiles;
  L.push("## Difficulty profiles");
  L.push("");
  L.push("| Profile | AP | Mistake % | Look-ahead | Focus fire | seqCost | beliefDecay |");
  L.push("|---|---:|---:|---:|:--:|---:|---:|");
  Object.keys(dp).forEach(function (k) {
    const p = dp[k];
    L.push("| " + k + " | " + p.ap + " | " + pct(p.mistakeChance) + " | " + p.lookaheadDepth + " | " + (p.focusFire ? "yes" : "no") + " | " + p.seqCost + " | " + p.beliefDecay + " |");
  });
  L.push("");
  L.push("Lower `seqCost` lets harder AIs chain longer action sequences; `beliefDecay` rises so tougher AIs remember spotted enemies longer.");
  L.push("");

  // Weapons
  const wp = R.weapons, wNames = Object.keys(wp);
  L.push("## Weapon variants (" + wNames.length + ")");
  L.push("");
  L.push("| Weapon | Class | Damage | Range | Slots |");
  L.push("|---|---|---:|---:|---:|");
  wNames.forEach(function (n) {
    const w = wp[n];
    L.push("| " + n + " | " + w["class"] + " | " + w.dmg + " | " + w.range + " | " + w.slots + " |");
  });
  L.push("");
  L.push("Slot cost = dmg × range, ×1.5 for railguns. Weapons are swappable between hulls at stations (DESIGN §3.3).");
  L.push("");

  // Ship roster
  const specs = R.shipSpecs, sNames = Object.keys(specs);
  L.push("## Ship roster (" + sNames.length + " specs)");
  L.push("");
  L.push("Costs are ×100 scale (DESIGN §4.5); crew = ⌈cost ÷ 100⌉. Capacity equals the slot total of the default loadout.");
  L.push("");
  L.push("| # | Ship | HP | Move | FP | RNG | SCN | Weapon | Slots | Crew | Cost | Flags |");
  L.push("|---:|---|---:|---:|---:|---:|---:|---|---:|---:|---:|---|");
  sNames.forEach(function (n, i) {
    const s = specs[n];
    const load = s.defaultLoadout.length ? s.defaultLoadout.join(", ") : "—";
    const flags = s.flags.map(function (f) { return "`" + f + "`"; }).join(", ");
    L.push("| " + (i + 1) + " | " + n + " | " + s.hp + " | " + s.move + " | " + s.firepower + " | " + s.range + " | " + s.scan + " | " + load + " | " + s.capacity + " | " + s.crew + " | " + fmt(s.cost) + " | " + flags + " |");
  });
  L.push("");

  // Ability flags
  const fd = R.flagDescriptions;
  L.push("## Ability and status flags");
  L.push("");
  Object.keys(fd).forEach(function (k) {
    L.push("- **`" + k + "`** — " + fd[k]);
  });
  L.push("");

  // Campaign start
  const st = C.campaign.start;
  L.push("## Campaign start");
  L.push("");
  L.push("Wallet " + fmt(st.wallet) + " ⒸB; starting fleet: " + st.startFleet.join(", ") + ". Cargo: goods " + st.cargo.goods + " / fuel " + st.cargo.fuel + " / crew " + st.cargo.crew + " / parts " + st.cargo.parts + ". Battle corner capacity " + st.battle.cornerCapacity + " deployed (overflow → battle reserve). Start location `" + st.map.locationId + "`; clock month " + st.clock.month + ", year " + st.clock.year + ".");
  L.push("");

  // Campaign escalation
  const levels = C.levels;
  L.push("## Campaign escalation (" + levels.length + " sectors)");
  L.push("");
  L.push("| Sector | Doctrine | Player ⒸB start/income | Enemy ⒸB start/income | Comp. budget | Asteroids | Nebulae |");
  L.push("|---|---|---:|---:|---:|---|---|");
  levels.forEach(function (lv) {
    L.push("| " + lv.tag + " | " + lv.aiDoctrine + " | " + fmt(lv.t1StartingCredits) + " / " + fmt(lv.t1Income) + " | " + fmt(lv.t2StartingCredits) + " / " + fmt(lv.t2Income) + " | " + fmt(lv.t2CompositionBudget) + " | " + lv.asteroidClusters.count + " (size " + lv.asteroidClusters.clusterSizeMin + "–" + lv.asteroidClusters.clusterSizeMax + ") | " + lv.nebulaPatches.count + " (size " + lv.nebulaPatches.patchSizeMin + "–" + lv.nebulaPatches.patchSizeMax + ") |");
  });
  L.push("");
  L.push("Enemy force composition per sector:");
  L.push("");
  levels.forEach(function (lv) {
    L.push("- **" + lv.title + "** — fixed spawn: " + lv.t2SpawnList.join(", ") + ". Composition budget " + fmt(lv.t2CompositionBudget) + " ⒸB buys from " + lv.t2ArchetypePool.join(", ") + ".");
  });
  L.push("");

  return L.join("\n") + "\n";
}

function main() {
  const arg = process.argv[2];
  const outPath = path.join(REPO_ROOT, OUT_REL);
  if (arg === "--check") {
    const current = fs.readFileSync(outPath, "utf8");
    const m = current.match(/^# Game Balance — Seek & Destroy \((v\d+)\)$/m);
    if (!m) {
      console.error("generate_game_balance --check: no (vNN) title stamp in " + OUT_REL);
      process.exit(2);
    }
    const fresh = generateGameBalance(m[1]);
    if (fresh === current) {
      console.log("generate_game_balance --check: OK — " + OUT_REL + " matches regeneration (" + m[1] + ")");
      process.exit(0);
    }
    console.error("generate_game_balance --check: STALE — " + OUT_REL + " differs from regeneration (" + m[1] + ")");
    process.exit(1);
  }
  if (!arg || !/^v\d+$/.test(arg)) {
    console.error("usage: node dev/scripts/generate_game_balance.js vNN | --check");
    process.exit(2);
  }
  fs.writeFileSync(outPath, generateGameBalance(arg));
  console.log("wrote " + OUT_REL + " (" + arg + ")");
}

if (require.main === module) main();
module.exports = { generateGameBalance };
