#!/usr/bin/env bash
# Snapshot every git version tag (vNN) into /home/ubuntu/snd-versions/vNN/
# so each version is reachable at https://seek-and-destroy.abacusai.cloud/vNN/
#
# The live root (/) always serves the working tree (the latest version).
# Re-run this after tagging a new version:  bash deploy/snapshot_versions.sh
set -euo pipefail

REPO="/home/ubuntu/seek-and-destroy"
DEST="/home/ubuntu/snd-versions"
cd "$REPO"

mkdir -p "$DEST"

# Enumerate version tags matching v<number>, newest sorting handled by nginx/listing.
# Use the full refname and strip refs/tags/ so tag names stay correct even when a
# branch shares the name (otherwise git disambiguates to "tags/v71").
mapfile -t TAGS < <(git for-each-ref --format='%(refname)' refs/tags/ | sed 's#^refs/tags/##' | grep -E '^v[0-9]+$' | sort -V)

for t in "${TAGS[@]}"; do
    out="$DEST/$t"
    rm -rf "$out"
    mkdir -p "$out"
    # Extract the exact tracked tree of the tag (binary .pak assets included).
    git archive "refs/tags/$t" | tar -x -C "$out"
    echo "snapshot: $t -> $out ($(find "$out" -type f | wc -l) files)"
done

# Redirect the bare root (/) to the highest version, generated into an include
# the vhost loads. 302 (not 301) so browsers re-check after each version bump and
# don't pin an old version in their cache. The redirect changes the address bar,
# so visitors land on — and keep seeing — /vNN/ in the URL.
LATEST="${TAGS[-1]}"
cat > "$DEST/root_redirect.conf" <<EOF
# Auto-generated by deploy/snapshot_versions.sh — do not edit by hand.
location = / { return 302 /$LATEST/; }
EOF
# Drop the obsolete /latest include if an older run left one behind.
rm -f "$DEST/latest.conf"
echo "root (/) -> /$LATEST/"

echo "Done. Versions available: ${TAGS[*]}"
echo "Reload nginx to apply: sudo nginx -t && sudo systemctl reload nginx"
